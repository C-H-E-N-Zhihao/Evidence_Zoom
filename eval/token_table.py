"""One table of tokens and dollars per correct answer across saved runs, re-scored with the current harness code.

    python -m eval.token_table --out eval/results/TOKEN_TABLE.md \
        --row "Receipts (CORD 241) | eval/results/receipts_v1_ladder/run_*.json" \
        --row "Receipts (CORD 241) | eval/results/receipts_v1_full/run_*.json" ...

Each --row is "<set label> | <glob of run JSONs>[ | <pipeline name>[ | <item file to restrict to>]]". Every pipeline found in the matched runs
gets its own line unless a pipeline name is given. Several run files in one row (e.g. one per layout) are pooled.
Results are joined to items by question_id; older runs without it are paired in run order (items grouped by image
in first-appearance order, the order run_eval uses). Rows whose join is incomplete are flagged, not dropped.

Columns follow codex-guanyu's token score (token-score, b5c9037): correct ANSWERS exclude correct handoffs; tokens are
provider-reported input (image + text + cache read/write) + output on cloud calls; local OCR/GPU is listed apart.
"""
from __future__ import annotations

import argparse
import glob
import json
from collections import defaultdict
from pathlib import Path

from .metrics import summarize
from .run_eval import load_items
from .schema import PipelineResult

ROOT = Path(__file__).parent.parent.absolute()  # not resolve(): keep the mount path the globs use


def _items_for(run: dict):
    p = Path(run["meta"]["items"])
    p = p if p.is_absolute() else ROOT / p
    if not p.exists() and (p.parent / "items.jsonl").exists():
        p = p.parent / "items.jsonl"  # an uncommitted subset file: the full set is a superset; results join by question_id
    return load_items(p)


def _qids(path: str) -> set[str]:
    """Question ids of an item file (.jsonl) or of the results in a run JSON."""
    text = (ROOT / path).read_text()
    if path.endswith(".json"):
        return {d.get("question_id") for rep in json.loads(text)["report"].values() for d in rep.get("results", [])}
    return {json.loads(l)["question_id"] for l in text.splitlines() if l.strip()}


def _run_order(items):
    by_img: dict[str, list] = defaultdict(list)
    for it in items:
        by_img[it.image_id].append(it)
    return [it for its in by_img.values() for it in its]


def pairs_for(run_paths: list[str], only: str | None):
    out: dict[str, dict] = {}
    for rp in run_paths:
        run = json.loads(Path(rp).read_text())
        items = _items_for(run)
        by_qid = {it.question_id: it for it in items}
        order = _run_order(items)
        for name, rep in run["report"].items():
            if only and name != only:
                continue
            agg = out.setdefault(name, {"pairs": [], "unmatched": 0, "complete": True, "runs": [], "commits": set()})
            agg["runs"].append(rp)
            agg["commits"].add(run["meta"].get("commit"))
            agg["complete"] &= bool(rep.get("complete", True)) and not rep.get("aborted")
            for k, d in enumerate(rep.get("results", [])):
                r = PipelineResult.from_dict(d)
                it = by_qid.get(r.question_id) if r.question_id else (order[k] if k < len(order) else None)
                if it is None:
                    agg["unmatched"] += 1
                    continue
                agg["pairs"].append((it, r))
    return out


def fmt(v, kind):
    if v is None:
        return "–"
    return {"int": f"{v:,}", "usd": f"${v:.5f}", "f3": f"{v:.3f}", "tok": f"{v:,.0f}"}[kind]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--row", action="append", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    lines = ["# Tokens per correct answer, all compared runs (re-scored with the same harness code)", "",
             "Generated by `python -m eval.token_table` from the committed run JSONs. Correct answers exclude correct "
             "handoffs (abstaining when the answer is not in the image). Cloud tokens = provider-reported input "
             "(image + text + cache) + output on API calls; all model tokens adds on-device (vLLM/Ollama) model calls. "
             "Only rows approved by the release reviewer may be quoted; "
             "see docs/NARRATIVE.md §3.", "",
             "| set | pipeline | n | correct answers | correct handoffs | wrong | other handoffs | ANLS | "
             "cloud tokens / correct | all model tokens / correct | $ / correct | $ total | complete |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for spec in a.row:
        parts = [s.strip() for s in spec.split("|")]
        label, pat, only = parts[0], parts[1], (parts[2] if len(parts) > 2 and parts[2] else None)
        keep = _qids(parts[3]) if len(parts) > 3 and parts[3] else None  # restrict to another item file's / run's questions
        paths = sorted(glob.glob(str(ROOT / pat)))
        if not paths:
            lines.append(f"| {label} | (no runs match `{pat}`) | | | | | | | | | | | |")
            continue
        for name, agg in pairs_for(paths, only).items():
            if keep is not None:
                agg["pairs"] = [(i, r) for i, r in agg["pairs"] if i.question_id in keep]
            s = summarize(agg["pairs"])["all"] if agg["pairs"] else {}
            if not s:
                continue
            correct_handoffs = s["correct"] - s["correct_answered"]
            other_handoffs = s["handoffs"] - correct_handoffs
            ok = agg["complete"] and not agg["unmatched"]
            allpc = ((s["cloud_tokens_total"] + s["local_tokens_total"]) / s["correct_answered"]
                     if s["correct_answered"] else None)  # on-device rows: local GPU model tokens count here
            lines.append(
                f"| {label} | `{name}` | {s['n']} | {s['correct_answered']} | {correct_handoffs} | {s['wrong_answers']} | "
                f"{other_handoffs} | {fmt(s.get('anls'), 'f3')} | {fmt(s['cloud_tokens_per_correct'], 'tok')} | "
                f"{fmt(allpc, 'tok')} | "
                f"{fmt(s['cost_usd_per_correct'], 'usd')} | {fmt(s['cost_usd_total'], 'usd')} | "
                f"{'yes' if ok else 'NO (' + str(agg['unmatched']) + ' unmatched)'} |")
    lines += ["", "Run files: " + "; ".join(f"`{r}`" for spec in a.row
                                           for r in sorted(glob.glob(str(ROOT / spec.split('|')[1].strip()))))]
    Path(a.out).write_text("\n".join(lines).replace(str(ROOT) + "/", "") + "\n")
    print("\n".join(lines[:200]))


if __name__ == "__main__":
    main()
